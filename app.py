# Create a validation split (e.g., train up to 2014, validate on 2015-2018)
train_df = india_df[india_df["Year"] <= 2014]
val_actual_df = india_df[india_df["Year"] > 2014]

# Fit on training data
train_model = Holt(
    train_df["Aquaculture production (metric tons)"].to_numpy(),
    initialization_method="estimated"
).fit(optimized=True)

# Predict validation period (4 years: 2015 to 2018)
val_predictions = train_model.forecast(len(val_actual_df))

# Create validation_df
validation_df = pd.DataFrame({
    "Year": val_actual_df["Year"].values,
    "Actual Production": val_actual_df["Aquaculture production (metric tons)"].values,
    "Predicted Production": val_predictions
})

# Save the validation results
validation_df.to_csv("model_validation_results.csv", index=False)

